const populatedPluginsJs = `// Generated by RPG Maker.
var $plugins =
[
{"name":"SomePlugin","status":true,"description":"","parameters":{}}
];
`

// writeGameFile creates a file (and its parent dirs) under a game root.
func writeGameFile(t *testing.T, root string, rel string, content string) string {
	t.Helper()
	full := path.Join(root, rel)
	if err := os.MkdirAll(path.Dir(full), 0o777); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(content), 0o666); err != nil {
		t.Fatal(err)
	}
	return full
}

func engineByName(t *testing.T, name string) *RPGMakerEngineType {
	t.Helper()
	for i := range RPGMakerEngineTypes {
		if RPGMakerEngineTypes[i].Name == name {
			return &RPGMakerEngineTypes[i]
		}
	}
	t.Fatalf("engine %q not found", name)
	return nil
}

