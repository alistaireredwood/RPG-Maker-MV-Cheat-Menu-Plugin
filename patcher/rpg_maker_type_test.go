func TestMZPostPatchCopiesPluginFile(t *testing.T) {
	dir := t.TempDir()
	writeGameFile(t, dir, "www/js/plugins/Cheat_Menu.js", "plugin v1")
	writeGameFile(t, dir, "js/plugins/.keep", "")

	engineByName(t, "MZ").PostPatch(dir, "Cheat_Menu")

	got, err := os.ReadFile(path.Join(dir, "js/plugins/Cheat_Menu.js"))
	if err != nil {
		t.Fatal("plugin file was not copied:", err)
	}
	if string(got) != "plugin v1" {
		t.Fatalf("unexpected copy content: %q", got)
	}
}

func TestMZPostPatchRefreshesExistingCopy(t *testing.T) {
	dir := t.TempDir()
	writeGameFile(t, dir, "www/js/plugins/Cheat_Menu.js", "plugin v2")
	writeGameFile(t, dir, "js/plugins/Cheat_Menu.js", "plugin v1")

	engineByName(t, "MZ").PostPatch(dir, "Cheat_Menu")

	got, err := os.ReadFile(path.Join(dir, "js/plugins/Cheat_Menu.js"))
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != "plugin v2" {
		t.Fatalf("expected refreshed copy, got %q", got)
	}
}

func TestMVHasNoPostPatch(t *testing.T) {
	if engineByName(t, "MV").PostPatch != nil {
		t.Fatal("MV must not define a PostPatch step")
	}
}
