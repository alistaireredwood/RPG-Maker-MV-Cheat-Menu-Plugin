func TestInjectIntoEmptyArray(t *testing.T) {
	dir := t.TempDir()
	pluginsJs := writeGameFile(t, dir, "js/plugins.js", "var $plugins = [];\n")

	if result := InjectPatchPlugin(pluginsJs, "Cheat_Menu", false); result != Patched {
		t.Fatalf("expected Patched, got %v", result)
	}

	content, err := os.ReadFile(pluginsJs)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(content), `"name":"Cheat_Menu"`) {
		t.Fatalf("plugin not injected: %s", content)
	}
}

func TestInjectIntoPopulatedArray(t *testing.T) {
	dir := t.TempDir()
	pluginsJs := writeGameFile(t, dir, "js/plugins.js", populatedPluginsJs)

	if result := InjectPatchPlugin(pluginsJs, "Cheat_Menu", false); result != Patched {
		t.Fatalf("expected Patched, got %v", result)
	}

	content, err := os.ReadFile(pluginsJs)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(content), `"name":"SomePlugin"`) ||
		!strings.Contains(string(content), `"name":"Cheat_Menu"`) {
		t.Fatalf("expected both plugins present: %s", content)
	}
}

func TestInjectedFileIsStillParseable(t *testing.T) {
	dir := t.TempDir()
	pluginsJs := writeGameFile(t, dir, "js/plugins.js", populatedPluginsJs)

	InjectPatchPlugin(pluginsJs, "Cheat_Menu", false)

	// a second injection of a different plugin re-parses the patched file
	if result := InjectPatchPlugin(pluginsJs, "Other_Plugin", false); result != Patched {
		t.Fatalf("patched file no longer parseable, got %v", result)
	}
}

func TestInjectAlreadyPatched(t *testing.T) {
	dir := t.TempDir()
	pluginsJs := writeGameFile(t, dir, "js/plugins.js", populatedPluginsJs)

	InjectPatchPlugin(pluginsJs, "Cheat_Menu", false)
	before, err := os.ReadFile(pluginsJs)
	if err != nil {
		t.Fatal(err)
	}

	if result := InjectPatchPlugin(pluginsJs, "Cheat_Menu", false); result != AlreadyPatched {
		t.Fatalf("expected AlreadyPatched, got %v", result)
	}

	after, err := os.ReadFile(pluginsJs)
	if err != nil {
		t.Fatal(err)
	}
	if string(after) != string(before) {
		t.Fatal("plugins.js must not change when already patched")
	}
}

