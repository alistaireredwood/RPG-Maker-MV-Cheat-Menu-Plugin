// Backup behaviour
/////////////////////////////////////////////////

func TestBackupHoldsOriginalContent(t *testing.T) {
	dir := t.TempDir()
	pluginsJs := writeGameFile(t, dir, "js/plugins.js", populatedPluginsJs)

	if result := InjectPatchPlugin(pluginsJs, "Cheat_Menu", true); result != Patched {
		t.Fatalf("expected Patched, got %v", result)
	}

	backup, err := os.ReadFile(pluginsJs + ".bak")
	if err != nil {
		t.Fatal("backup not created:", err)
	}
	if string(backup) != populatedPluginsJs {
		t.Fatal("backup must hold the original unpatched content")
	}
}

func TestNoBackupWhenDisabled(t *testing.T) {
	dir := t.TempDir()
	pluginsJs := writeGameFile(t, dir, "js/plugins.js", populatedPluginsJs)

	InjectPatchPlugin(pluginsJs, "Cheat_Menu", false)

	if _, err := os.Stat(pluginsJs + ".bak"); err == nil {
		t.Fatal("backup must not be created when disabled")
	}
}

func TestNoBackupWhenAlreadyPatched(t *testing.T) {
	dir := t.TempDir()
	pluginsJs := writeGameFile(t, dir, "js/plugins.js", populatedPluginsJs)

	InjectPatchPlugin(pluginsJs, "Cheat_Menu", false)
	if result := InjectPatchPlugin(pluginsJs, "Cheat_Menu", true); result != AlreadyPatched {
		t.Fatalf("expected AlreadyPatched, got %v", result)
	}

	if _, err := os.Stat(pluginsJs + ".bak"); err == nil {
		t.Fatal("backup must not be written when nothing was injected")
	}
}

